-- LLZ Air Ranking BW
-- Run in Supabase Dashboard > SQL Editor.
create table if not exists public.air_results (
  id bigint generated by default as identity primary key,
  athlete_name text not null check (char_length(trim(athlete_name)) between 2 and 100),
  club text not null check (char_length(trim(club)) between 2 and 120),
  score_tenths integer not null check (score_tenths between 0 and 6540),
  month text not null check (month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  constraint one_submission_per_athlete_month unique (athlete_name, month)
);

alter table public.air_results enable row level security;

-- Anyone with the public portal link can read only approved results.
drop policy if exists "Anyone can read approved results" on public.air_results;
create policy "Anyone can read approved results"
on public.air_results for select
to anon, authenticated
using (status = 'approved');

-- Public submissions are always pending; users cannot self-approve via the insert policy.
drop policy if exists "Anyone can submit pending results" on public.air_results;
create policy "Anyone can submit pending results"
on public.air_results for insert
to anon, authenticated
with check (status = 'pending');

-- No public UPDATE or DELETE policies are intentionally created.
